import express from 'express';
import helmet from 'helmet';
import rateLimit from 'express-rate-limit';
import corsMiddleware from './config/cors.js';
import authRoutes from './routes/authRoutes.js';
import projectIdeaRoutes from './routes/projectIdeaRoutes.js';
import generatedIdeaRoutes from './routes/generatedIdeaRoutes.js';
import savedProjectRoutes from './routes/savedProjectRoutes.js';
import versionRoutes from './routes/versionRoutes.js';
import aiRoutes from './routes/aiRoutes.js';
import tinyFishRoutes from './routes/tinyFishRoutes.js';
import { notFound } from './middleware/notFound.js';
import { errorHandler } from './middleware/errorHandler.js';

const app = express();
app.disable('x-powered-by');
app.use(helmet({ crossOriginResourcePolicy: { policy: 'cross-origin' } }));
app.use(corsMiddleware);
app.use(express.json({ limit: '2mb' }));
app.use(express.urlencoded({ extended: true, limit: '2mb' }));
app.use('/api', rateLimit({ windowMs: 15 * 60 * 1000, limit: 300, standardHeaders: 'draft-7', legacyHeaders: false }));
app.get('/api/health', (_req, res) => res.json({ success: true, status: 'ok', service: 'forgeflow-api' }));
app.use('/api/auth', authRoutes);
app.use('/api/project-ideas', projectIdeaRoutes);
app.use('/api/generated-ideas', generatedIdeaRoutes);
app.use('/api/saved-projects', savedProjectRoutes);
app.use('/api/project-versions', versionRoutes.projectVersions);
app.use('/api/feature-versions', versionRoutes.featureVersions);
app.use('/api/ai', aiRoutes);
app.use('/api/web', tinyFishRoutes);
app.use(notFound);
app.use(errorHandler);
export default app;
