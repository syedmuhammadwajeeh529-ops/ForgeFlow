
-- =========================================================
-- ForgeFlow Database
-- Database: MySQL 8.0+
-- =========================================================

CREATE DATABASE IF NOT EXISTS forgeflow
    CHARACTER SET utf8mb4
    COLLATE utf8mb4_unicode_ci;

USE forgeflow;

-- =========================================================
-- 1. USERS
-- Replaces Base44's built-in User entity and authentication.
-- =========================================================

CREATE TABLE IF NOT EXISTS users (
    id CHAR(36) PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role ENUM('admin', 'user') NOT NULL DEFAULT 'user',

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Revoked JWT hashes allow the API to invalidate sessions at logout.
CREATE TABLE IF NOT EXISTS revoked_tokens (
    token_hash CHAR(64) PRIMARY KEY,
    expires_at TIMESTAMP NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    INDEX idx_revoked_tokens_expiry (expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- =========================================================
-- 2. PROJECT IDEAS
-- Curated ideas available to everyone.
-- Only admins can create, update, or delete these.
-- =========================================================

CREATE TABLE IF NOT EXISTS project_ideas (
    id CHAR(36) PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    description TEXT NOT NULL,

    difficulty ENUM(
        'Beginner',
        'Intermediate',
        'Advanced'
    ) NOT NULL,

    category ENUM(
        'Web',
        'Mobile',
        'AI',
        'ML',
        'CLI',
        'Game',
        'API',
        'Data',
        'DevOps',
        'Other'
    ) NOT NULL,

    tech_stack JSON,
    is_curated BOOLEAN NOT NULL DEFAULT FALSE,
    tags JSON,

    created_by_id CHAR(36) NULL,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP,

    CONSTRAINT fk_project_ideas_creator
        FOREIGN KEY (created_by_id)
        REFERENCES users(id)
        ON DELETE SET NULL,

    INDEX idx_project_ideas_category (category),
    INDEX idx_project_ideas_difficulty (difficulty),
    INDEX idx_project_ideas_curated (is_curated),
    INDEX idx_project_ideas_filters_created (category, difficulty, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- =========================================================
-- 3. GENERATED IDEAS
-- Ideas generated by individual users.
-- Users can access their own ideas; admins can access all.
-- =========================================================

CREATE TABLE IF NOT EXISTS generated_ideas (
    id CHAR(36) PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    description TEXT NOT NULL,

    difficulty ENUM(
        'Beginner',
        'Intermediate',
        'Advanced'
    ) NULL,

    category VARCHAR(100) NOT NULL,

    tech_stack JSON,
    tags JSON,
    prompt TEXT,

    created_by_id CHAR(36) NOT NULL,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP,

    CONSTRAINT fk_generated_ideas_user
        FOREIGN KEY (created_by_id)
        REFERENCES users(id)
        ON DELETE CASCADE,

    INDEX idx_generated_ideas_owner (created_by_id),
    INDEX idx_generated_ideas_created (created_at),
    INDEX idx_generated_ideas_owner_created (created_by_id, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- =========================================================
-- 4. SAVED PROJECTS
-- Projects saved by users.
-- =========================================================

CREATE TABLE IF NOT EXISTS saved_projects (
    id CHAR(36) PRIMARY KEY,

    idea_id CHAR(36) NULL,

    title VARCHAR(255) NOT NULL,
    description TEXT NOT NULL,

    difficulty ENUM(
        'Beginner',
        'Intermediate',
        'Advanced'
    ) NULL,

    category VARCHAR(100) NULL,

    tech_stack JSON,

    code LONGTEXT,
    language VARCHAR(100) NOT NULL DEFAULT 'javascript',
    notes TEXT,

    current_version VARCHAR(100),

    status ENUM(
        'saved',
        'in_progress',
        'completed'
    ) NOT NULL DEFAULT 'saved',

    created_by_id CHAR(36) NOT NULL,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP,

    CONSTRAINT fk_saved_projects_user
        FOREIGN KEY (created_by_id)
        REFERENCES users(id)
        ON DELETE CASCADE,

    INDEX idx_saved_projects_owner (created_by_id),
    INDEX idx_saved_projects_status (status),
    INDEX idx_saved_projects_updated (updated_at),
    INDEX idx_saved_projects_owner_updated (created_by_id, updated_at),
    INDEX idx_saved_projects_owner_status (created_by_id, status),
    INDEX idx_saved_projects_owner_category (created_by_id, category)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- =========================================================
-- 5. PROJECT VERSIONS
-- Stores snapshots of saved projects.
-- =========================================================

CREATE TABLE IF NOT EXISTS project_versions (
    id CHAR(36) PRIMARY KEY,

    project_id CHAR(36) NOT NULL,

    label VARCHAR(100) NOT NULL,
    code LONGTEXT,
    language VARCHAR(100),
    notes TEXT,
    features LONGTEXT,

    created_by_id CHAR(36) NOT NULL,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP,

    CONSTRAINT fk_project_versions_project
        FOREIGN KEY (project_id)
        REFERENCES saved_projects(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_project_versions_user
        FOREIGN KEY (created_by_id)
        REFERENCES users(id)
        ON DELETE CASCADE,

    INDEX idx_project_versions_project (project_id),
    INDEX idx_project_versions_owner (created_by_id),
    INDEX idx_project_versions_created (created_at),
    INDEX idx_project_versions_project_owner_created (project_id, created_by_id, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- =========================================================
-- 6. FEATURE VERSIONS
-- Stores feature plans and their history.
-- =========================================================

CREATE TABLE IF NOT EXISTS feature_versions (
    id CHAR(36) PRIMARY KEY,

    project_id CHAR(36) NOT NULL,

    label VARCHAR(100) NOT NULL,
    features LONGTEXT,
    notes TEXT,

    created_by_id CHAR(36) NOT NULL,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP,

    CONSTRAINT fk_feature_versions_project
        FOREIGN KEY (project_id)
        REFERENCES saved_projects(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_feature_versions_user
        FOREIGN KEY (created_by_id)
        REFERENCES users(id)
        ON DELETE CASCADE,

    INDEX idx_feature_versions_project (project_id),
    INDEX idx_feature_versions_owner (created_by_id),
    INDEX idx_feature_versions_created (created_at),
    INDEX idx_feature_versions_project_owner_created (project_id, created_by_id, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
